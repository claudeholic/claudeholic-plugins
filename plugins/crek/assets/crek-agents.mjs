/**
 * crek-agents — which agent type and which model each CREK agent role starts with.
 *
 *   node crek-agents.mjs --config crek.config.json           # the plan, nothing written
 *   node crek-agents.mjs --config crek.config.json --sync    # the plan, project agent files updated
 *
 * The skills start their agents (job-scan: collecting agents, the login-board agent, deep-read and
 * scoring agents) as CREK's own agent types, defined in the plugin's agents/ directory. The model
 * comes from the config, never from the skill's text: `agents.model` for every role,
 * `agents.roles.<role>` for one role; neither set → `sonnet`, the newest Sonnet.
 *
 * Claude Code lets the session pass a model when it starts an agent, but only as an alias
 * (sonnet, opus, haiku, fable). A full model ID (claude-sonnet-5) or `inherit` can only stand in an
 * agent definition's `model` frontmatter, and the plugin's own definitions are fixed files. So:
 *
 *   - an alias → agent type `crek:<role>` (the plugin's definition), `model` = the alias, which the
 *     session passes with the Agent tool;
 *   - anything else → agent type `crek-<role>`, a copy of the plugin's definition with that `model`
 *     in the project's .claude/agents/ (the directory next to crek.config.json, or --project-dir).
 *     --sync writes it, rewrites it when the model or the plugin changed, and removes such copies
 *     when no role needs them any more (only files this script generated: they carry its marker).
 *     The session passes no `model` then (`"model": null`).
 *
 * Claude Code picks up a changed file in .claude/agents/ by itself, but not a .claude/agents/
 * directory created after the session started: when --sync creates the directory it says
 * `"restart_needed": true`, and until the restart the session uses each role's `fallback` (the
 * plugin's definition with the model's family alias, or with its own default when there is none).
 *
 * Output (JSON, always):
 *   {"agents": {"collector": {"subagent_type", "model", "configured", "from", "file"?, "file_status"?,
 *               "fallback"?}, "login_board": {...}, "assessor": {...}},
 *    "written": [...], "removed": [...], "restart_needed": false}
 *
 * Exit: 0 fine; 1 config errors in `agents` (printed to stderr, nothing written); 2 usage error.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PLUGIN_ROOT = resolve(HERE, '..');
export const PLUGIN_NAME = 'crek';
/** Role (config key) → the plugin's agent file and the name of a project copy. */
export const ROLES = {
  collector: { file: 'collector.md', name: 'collector' },
  login_board: { file: 'login-board.md', name: 'login-board' },
  assessor: { file: 'assessor.md', name: 'assessor' },
};
/** What the Agent tool's `model` parameter accepts. */
export const MODEL_ALIASES = ['sonnet', 'opus', 'haiku', 'fable'];
export const DEFAULT_MODEL = 'sonnet';
export const MARKER = '# generated by crek-agents.mjs (crek plugin) from crek.config.json agents — edits are overwritten';
// A model value as Claude Code's --model takes it: an alias, `inherit`, a model ID, with an
// optional [1m]; provider IDs (Bedrock, Vertex) may hold dots, colons, slashes and @.
const MODEL_RE = /^[A-Za-z0-9][A-Za-z0-9._:/@-]*(\[1m\])?$/;

const obj = (v) => (v && typeof v === 'object' && !Array.isArray(v) ? v : null);
const localName = (role) => `${PLUGIN_NAME}-${ROLES[role].name}`;

/** Errors, warnings and notes about `agents` in the config (crek-config-check prints them). */
export function agentProblems(cfg) {
  const errors = [];
  const warnings = [];
  const notes = [];
  const a = cfg?.agents;
  if (a === undefined) {
    notes.push(`agents is not set — CREK's agents run on ${DEFAULT_MODEL} (the newest Sonnet); set agents.model to change it`);
    return { errors, warnings, notes };
  }
  if (!obj(a)) {
    errors.push('agents must be an object {model, roles}');
    return { errors, warnings, notes };
  }
  for (const k of Object.keys(a)) {
    if (!['model', 'roles'].includes(k)) errors.push(`agents.${k} is not a known field — expected model, roles`);
  }
  const checkModel = (at, v) => {
    if (typeof v !== 'string' || !v.trim()) { errors.push(`${at} must be a non-empty string (e.g. sonnet or claude-sonnet-5)`); return; }
    if (!MODEL_RE.test(v)) { errors.push(`${at} is ${JSON.stringify(v)} — expected an alias (${MODEL_ALIASES.join(', ')}), inherit or a model ID such as claude-sonnet-5`); return; }
    if (!MODEL_ALIASES.includes(v) && v !== 'inherit' && !/claude/i.test(v) && !/^(sonnet|opus|haiku|fable)\[1m\]$/.test(v)) {
      warnings.push(`${at} is "${v}" — not an alias, not inherit and no "claude" in it; check that Claude Code knows this model`);
    }
  };
  if (a.model !== undefined) checkModel('agents.model', a.model);
  if (a.roles !== undefined) {
    if (!obj(a.roles)) errors.push(`agents.roles must be an object: ${Object.keys(ROLES).join(', ')} → model`);
    else {
      for (const [k, v] of Object.entries(a.roles)) {
        if (!ROLES[k]) errors.push(`agents.roles.${k} is not a CREK agent role — expected ${Object.keys(ROLES).join(', ')}`);
        else checkModel(`agents.roles.${k}`, v);
      }
    }
  }
  if (!errors.length) {
    const plan = agentPlan(cfg);
    const pinned = Object.entries(plan).filter(([, p]) => p.model === null).map(([r, p]) => `${r} (${p.configured})`);
    if (pinned.length) {
      notes.push(`agents: ${pinned.join(', ')} — not an alias, so the role runs from a project agent definition in .claude/agents/ that crek-agents.mjs --sync writes`);
    }
  }
  return { errors, warnings, notes };
}

/** The family alias of a model ID (claude-sonnet-5 → sonnet), or null. */
export function familyAlias(model) {
  const m = /(sonnet|opus|haiku|fable)/i.exec(String(model));
  return m ? m[1].toLowerCase() : null;
}

/** Per role: {subagent_type, model (the Agent tool's parameter, or null), configured, from}. */
export function agentPlan(cfg) {
  const a = obj(cfg?.agents) ?? {};
  const roles = obj(a.roles) ?? {};
  const plan = {};
  for (const role of Object.keys(ROLES)) {
    const [configured, from] = typeof roles[role] === 'string' && roles[role].trim()
      ? [roles[role].trim(), `agents.roles.${role}`]
      : typeof a.model === 'string' && a.model.trim()
        ? [a.model.trim(), 'agents.model']
        : [DEFAULT_MODEL, 'default'];
    if (MODEL_ALIASES.includes(configured)) {
      plan[role] = { subagent_type: `${PLUGIN_NAME}:${ROLES[role].name}`, model: configured, configured, from };
    } else {
      plan[role] = {
        subagent_type: localName(role),
        model: null,
        configured,
        from,
        file: join('.claude', 'agents', `${localName(role)}.md`),
        fallback: { subagent_type: `${PLUGIN_NAME}:${ROLES[role].name}`, model: familyAlias(configured) },
      };
    }
  }
  return plan;
}

/** The project copy of a role's plugin definition, with `model` set and the plugin root filled in. */
export function renderAgent(role, model, { pluginRoot = PLUGIN_ROOT } = {}) {
  const src = readFileSync(join(pluginRoot, 'agents', ROLES[role].file), 'utf8');
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(src);
  if (!m) throw new Error(`agents/${ROLES[role].file} has no frontmatter`);
  const front = m[1].split('\n').filter((l) => !/^(name|model):/.test(l));
  const body = m[2].replaceAll('${CLAUDE_PLUGIN_ROOT}', pluginRoot);
  return ['---', MARKER, `name: ${localName(role)}`, `model: ${JSON.stringify(model)}`, ...front, '---', body].join('\n');
}

/**
 * Brings the project's .claude/agents/ in line with the plan: writes the copies the plan needs,
 * removes generated copies it no longer needs. Returns {plan (with file_status), written, removed,
 * restart_needed}. With write=false nothing changes and file_status says what --sync would do.
 */
export function syncAgents(cfg, { projectDir, write = true, pluginRoot = PLUGIN_ROOT } = {}) {
  const plan = agentPlan(cfg);
  const dir = join(projectDir, '.claude', 'agents');
  const existed = existsSync(dir);
  const written = [];
  const removed = [];
  let created = false;
  for (const [role, p] of Object.entries(plan)) {
    if (p.model !== null) continue;
    const path = join(projectDir, p.file);
    const want = renderAgent(role, p.configured, { pluginRoot });
    const have = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (have === want) { p.file_status = 'ok'; continue; }
    if (have !== null && !have.includes(MARKER)) {
      // Someone's own file under our name: never overwritten.
      p.file_status = 'foreign';
      p.subagent_type = p.fallback.subagent_type;
      p.model = p.fallback.model;
      continue;
    }
    p.file_status = have === null ? 'missing' : 'stale';
    if (!write) continue;
    if (!existsSync(dir)) { mkdirSync(dir, { recursive: true }); created = true; }
    writeFileSync(path, want, { mode: 0o644 });
    written.push(p.file);
    p.file_status = 'written';
  }
  const needed = new Set(Object.values(plan).filter((p) => p.file && p.file_status !== 'foreign').map((p) => p.file));
  if (existed) {
    for (const f of readdirSync(dir)) {
      const rel = join('.claude', 'agents', f);
      if (!f.startsWith(`${PLUGIN_NAME}-`) || !f.endsWith('.md') || needed.has(rel)) continue;
      const path = join(dir, f);
      let text = '';
      try { text = readFileSync(path, 'utf8'); } catch { continue; }
      if (!text.includes(MARKER)) continue;
      if (write) { unlinkSync(path); removed.push(rel); } else removed.push(`${rel} (would be removed)`);
    }
  }
  return { plan, written, removed, restart_needed: created };
}

function usage(msg) {
  if (msg) console.error(`error: ${msg}`);
  console.error('usage: node crek-agents.mjs --config crek.config.json [--sync] [--project-dir DIR]');
  process.exit(2);
}

async function main(argv) {
  const opt = { config: 'crek.config.json', sync: false, projectDir: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--config') opt.config = argv[++i] ?? usage('--config needs a path');
    else if (a === '--sync') opt.sync = true;
    else if (a === '--project-dir') opt.projectDir = argv[++i] ?? usage('--project-dir needs a path');
    else if (a === '--help' || a === '-h') usage();
    else usage(`unknown argument ${a}`);
  }
  const configPath = resolve(opt.config);
  if (!existsSync(configPath)) usage(`${configPath} does not exist`);
  let cfg;
  try { cfg = JSON.parse(readFileSync(configPath, 'utf8')); } catch (err) { usage(`${configPath} is not valid JSON — ${err.message}`); }
  const { errors, warnings } = agentProblems(cfg);
  for (const w of warnings) console.error(`warning: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`error: ${e}`);
    process.exitCode = 1;
    return;
  }
  const projectDir = resolve(opt.projectDir ?? dirname(configPath));
  const { plan, written, removed, restart_needed } = syncAgents(cfg, { projectDir, write: opt.sync });
  const out = `${JSON.stringify({ agents: plan, written, removed, restart_needed }, null, 2)}\n`;
  await new Promise((ok) => process.stdout.write(out, ok));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((err) => { console.error(`error: ${err.stack ?? err}`); process.exit(1); });
}
